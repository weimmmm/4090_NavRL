"""Extract true pre-terminal observations for EVERY collision episode.

No simulation, inference, or training is rerun. Frames are strictly earlier
than the collision decision and retain their actual 0.16-second sample times.
The terminal position is the drone center, NOT a measured contact point.
"""
from __future__ import annotations

import argparse
import base64
import csv
from io import BytesIO
import json
from pathlib import Path
import zipfile

import numpy as np
from PIL import Image, ImageDraw, ImageFont

from visualize_sft_velocity import render_one


def png_range(image, path, maximum):
    values = np.clip(np.rint(image/maximum*255.), 0., 255.).astype(np.uint8)
    picture = Image.fromarray(values, mode="L")
    picture.save(path, optimize=True)
    buffer = BytesIO()
    picture.save(buffer, format="PNG", optimize=True)
    return "data:image/png;base64,"+base64.b64encode(buffer.getvalue()).decode("ascii")


def sector(azimuth):
    if abs(azimuth) <= 60:
        return "前方"
    if azimuth >= 120 or azimuth <= -120:
        return "后方"
    return "左侧" if azimuth > 0 else "右侧"


def render_frame(frame, front, panorama, output, maximum):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig = plt.figure(figsize=(5.6, 5.6), dpi=160, facecolor="white")
    ax = fig.add_axes((.025, .42, .95, .48))
    render_one(ax, {"frontal_range_m": front,
                    "command_ego_xyz_mps": frame["command_ego_xyz_mps"]}, maximum,
               origin=(.5, .5), gain=.16)
    fig.text(.5, .985, f"T - {frame['before_collision_s']:.3f} s | step {frame['physics_step']}",
             ha="center", va="top", fontsize=17)
    fig.text(.5, .345, f"Command speed = {frame['command_speed_mps']:.3f} m/s",
             ha="center", fontsize=21)
    x, y, z = frame["command_ego_xyz_mps"]
    fig.text(.5, .285, f"vx {x:+.3f}   vy {y:+.3f}   vz {z:+.3f} m/s",
             ha="center", fontsize=16)
    nearest = frame["nearest_range_m"]
    label = (f"Nearest 360 return = {nearest:.3f} m | az {frame['nearest_azimuth_deg']:+.1f} deg"
             if nearest is not None else "No finite LiDAR return")
    fig.text(.5, .225, label, ha="center", fontsize=14)
    pano = fig.add_axes((.025, .06, .95, .15))
    pano.imshow(panorama, cmap="gray", vmin=0, vmax=maximum, interpolation="nearest", aspect="auto")
    if frame["nearest_pano_pixel"] is not None:
        col, row = frame["nearest_pano_pixel"]
        pano.plot(col, row, "o", ms=8, mec="#0072bd", mfc="none", mew=2)
    pano.set_xticks([])
    pano.set_yticks([])
    for spine in pano.spines.values():
        spine.set_visible(False)
    fig.text(.5, .025, "360 deg: Back | Left | Front | Right | Back", ha="center", fontsize=14)
    fig.savefig(output, dpi=160)
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--trajectory", type=Path, required=True)
    parser.add_argument("--metrics", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--frames", type=int, default=6)
    parser.add_argument("--lidar-range", type=float, default=5.)
    args = parser.parse_args()
    if args.frames <= 0:
        parser.error("Positive frame count required")
    if args.output.exists():
        raise FileExistsError("Preserve prior collision reports; select another output directory")
    args.output.mkdir(parents=True)
    metrics = json.loads(args.metrics.read_text())
    if metrics["action_frame"] not in {"yaw_only_ego_flu", "current_observation_yaw_only_ego_flu"}:
        raise ValueError("Velocity frame must be yaw-only ego FLU")
    # This trusted archive was generated by this project's evaluator.
    data = np.load(args.trajectory, allow_pickle=True)
    steps = data["lidar_step"].astype(np.int64)
    images = data["lidar_image"]
    commands = data["ego_velocity_command"]
    states = data["root_state_wxyz"]
    dt = float(data["physics_dt"])
    routes = np.flatnonzero(data["outcome"] == "collision")
    if len(routes) != int(metrics["counts"]["collision"]):
        raise ValueError("Collision trajectory count differs from summary")
    azimuth = (np.arange(108)*360./108.+180.) % 360.-180.
    front_order = np.flatnonzero(np.abs(azimuth) <= 60.+1e-5)
    front_order = front_order[np.argsort(azimuth[front_order])[::-1]]
    full_order = np.argsort(azimuth)[::-1]
    inverse_order = np.argsort(full_order)
    report = {"checkpoint": metrics["checkpoint"], "checkpoint_step": metrics["checkpoint_step"],
              "source_trajectory": str(args.trajectory), "physics_dt_s": dt,
              "frames_per_collision": args.frames, "lidar_range_m": args.lidar_range,
              "frame_semantics": "real recorded LiDAR, strictly before terminal decision",
              "collision_position_semantics": "drone center at range-based collision decision, NOT contact point",
              "arrow_semantics": "ego XY HUD; +x forward/up on HUD, +y left; z listed separately",
              "nearest_marker_semantics": "closest return in this observed frame, not a verified impact point",
              "routes": []}
    csv_rows, saved_images = [], []
    from matplotlib import font_manager
    font = ImageFont.truetype(font_manager.findfont("DejaVu Sans"), 44)
    small_font = ImageFont.truetype(font_manager.findfont("DejaVu Sans"), 34)
    for route in routes.tolist():
        terminal = int(data["terminal_step"][route])
        indices = np.flatnonzero(steps < terminal)[-args.frames:]
        if len(indices) != args.frames:
            raise ValueError(f"Route {route} has fewer than {args.frames} pre-collision observations")
        folder = args.output/f"route_{route:03d}"
        folder.mkdir()
        episode = {"route": route, "collision_step": terminal,
                   "collision_time_s": terminal*dt,
                   "terminal_drone_center_world_xyz_m": states[terminal, route, :3].astype(float).tolist(),
                   "frames": []}
        panels = []
        for index in indices.tolist():
            step = int(steps[index])
            if not step < terminal or step % 10:
                raise ValueError("Invalid observation/terminal alignment")
            raw = images[index, route]
            distance = (raw[0, :, :18].astype(np.float32)+1.)*(args.lidar_range/2.)
            valid = raw[1, :, :18] > 0
            nearest_values = np.where(valid, distance, np.inf)
            ray, elevation = np.unravel_index(nearest_values.argmin(), nearest_values.shape)
            nearest = float(nearest_values[ray, elevation])
            distance[~valid] = args.lidar_range
            front = distance[front_order].T[::-1]
            panorama = distance[full_order].T[::-1]
            command = commands[step, route].astype(float)
            frame = {"physics_step": step, "observation_index": index,
                     "before_collision_s": (terminal-step)*dt,
                     "command_ego_xyz_mps": command.tolist(),
                     "command_speed_mps": float(np.linalg.norm(command)),
                     "measured_speed_mps": float(np.linalg.norm(states[step, route, 7:10])),
                     "nearest_range_m": nearest if np.isfinite(nearest) else None,
                     "nearest_azimuth_deg": float(azimuth[ray]) if np.isfinite(nearest) else None,
                     "nearest_sector": sector(float(azimuth[ray])) if np.isfinite(nearest) else "无回波",
                     "nearest_pano_pixel": [int(inverse_order[ray]), int(17-elevation)] if np.isfinite(nearest) else None}
            basename = f"step_{step:04d}"
            frame["front_image_uri"] = png_range(front, folder/(basename+"_front.png"), args.lidar_range)
            frame["panorama_image_uri"] = png_range(panorama, folder/(basename+"_360.png"), args.lidar_range)
            annotated = folder/(basename+"_annotated.png")
            render_frame(frame, front, panorama, annotated, args.lidar_range)
            frame["annotated_image"] = str(annotated)
            panels.append(Image.open(annotated).convert("RGB"))
            episode["frames"].append(frame)
            csv_rows.append({"route": route, "collision_step": terminal, "observation_step": step,
                             "before_collision_s": frame["before_collision_s"],
                             "vx_mps": command[0], "vy_mps": command[1], "vz_mps": command[2],
                             "command_speed_mps": frame["command_speed_mps"],
                             "measured_speed_mps": frame["measured_speed_mps"],
                             "nearest_range_m": frame["nearest_range_m"],
                             "nearest_azimuth_deg": frame["nearest_azimuth_deg"]})
            saved_images.append((route, step, raw.copy(), command))
        cols, rows = 3, (len(panels)+2)//3
        width, height = panels[0].size
        canvas = Image.new("RGB", (cols*width, rows*height+140), "white")
        draw = ImageDraw.Draw(canvas)
        draw.text((24, 14), f"Route {route} | Collision decision: step {terminal}, {terminal*dt:.3f} s", font=font, fill="black")
        for i, panel in enumerate(panels):
            canvas.paste(panel, ((i%cols)*width, 80+(i//cols)*height))
        draw.text((24, canvas.height-52), "Red: XY command | Blue: nearest observed return, not contact point | Black: near, white: far/no hit", font=small_font, fill="black")
        contact = args.output/f"collision_route_{route:03d}.png"
        canvas.save(contact, optimize=True)
        episode["contact_sheet"] = str(contact)
        report["routes"].append(episode)
        (args.output/f"viewer_route_{route:03d}.json").write_text(json.dumps(episode, separators=(",", ":"), ensure_ascii=False))
    report_path = args.output/"collision_frames.json"
    report_path.write_text(json.dumps(report, indent=2, ensure_ascii=False)+"\n")
    with (args.output/"collision_frames.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(csv_rows[0]))
        writer.writeheader()
        writer.writerows(csv_rows)
    np.savez_compressed(args.output/"selected_lidar_frames.npz",
                        route=np.asarray([r[0] for r in saved_images]),
                        physics_step=np.asarray([r[1] for r in saved_images]),
                        lidar_image=np.stack([r[2] for r in saved_images]),
                        command_ego_xyz_mps=np.stack([r[3] for r in saved_images]))
    archive = args.output/"all_collision_preframes.zip"
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as zipped:
        for path in sorted(args.output.glob("collision_route_*.png")):
            zipped.write(path, path.name)
        for name in ("collision_frames.csv", "selected_lidar_frames.npz"):
            zipped.write(args.output/name, name)
    print(json.dumps({"collision_routes": routes.tolist(), "frames_per_collision": args.frames,
                      "total_frames": len(csv_rows), "archive": str(archive),
                      "last_observation_lead_s": {r["route"]:r["frames"][-1]["before_collision_s"] for r in report["routes"]}}))


if __name__ == "__main__":
    main()
