"""Once-only online chunk labels from PPO corrections on STUDENT states.

This is NOT a PPO counterfactual rollout. The student flies every command;
the teacher is queried at each actual visited state. Only the chunk-start
student observation becomes an input. Later observations/privileged features
are used by PPO for TARGETS only. Labels share the chunk-start yaw frame.
After ten commands, one learner update consumes that chunk exactly once.
"""
import os
from pathlib import Path

import numpy as np
import torch

from lidar_wam.runner.online_supervision import online_teacher_target, target_diagnostics


class ChunkTeacherBuffer:
    """One live chunk, not a replay cache; it cannot be consumed twice."""

    def __init__(self, latent, goal, proprio, quaternion, selected, version, physics, mode):
        n = len(latent)
        if len(goal) != n or len(proprio) != n or quaternion.shape != (n, 4):
            raise ValueError("Chunk-start input rows differ")
        self.inputs = {key: value.detach().float().cpu().numpy().copy()
                       for key, value in (("latent", latent), ("goal", goal), ("proprio", proprio))}
        self.quaternion = quaternion.detach().clone()
        self.selected = selected.clone()
        self.version, self.physics, self.mode = int(version), int(physics), mode
        self.raw = latent.new_zeros(n, 10, 3, dtype=torch.float32)
        self.target = torch.zeros_like(self.raw)
        self.mask = torch.zeros(n, 10, dtype=torch.bool, device=latent.device)
        self.recorded = 0
        self.consumed = False

    def record(self, index, raw_target_in_start_frame, valid):
        if self.consumed or index != self.recorded or not 0 <= index < 10:
            raise ValueError("Chunk labels must be recorded once, sequentially")
        if raw_target_in_start_frame.shape != self.raw[:, index].shape or valid.shape != self.selected.shape:
            raise ValueError("Teacher label/validity rows differ from chunk-start inputs")
        target = online_teacher_target(raw_target_in_start_frame, self.mode)
        valid = valid & self.selected & torch.isfinite(target).all(-1)
        self.raw[:, index] = raw_target_in_start_frame
        self.target[:, index] = torch.where(valid[:, None], target, torch.zeros_like(target))
        self.mask[:, index] = valid
        self.recorded += 1

    def consume(self, version, physics):
        if self.consumed or self.recorded != 10:
            raise ValueError("Only a complete, unconsumed chunk can train")
        if version != self.version or physics != self.physics+10:
            raise ValueError("Labels were generated by another student version or chunk")
        self.consumed = True
        keep = self.mask[:, 0]
        cpu_keep = keep.cpu().numpy()
        batch = {key: values[cpu_keep] for key, values in self.inputs.items()}
        batch.update(target=self.target[keep].cpu().numpy(),
                     target_mask=self.mask[keep].float().cpu().numpy())
        return batch, target_diagnostics(self.raw, self.target, self.mask)


def run_chunk_supervised(cfg, env, base_policy, lee, checkpoint, teacher, teacher_sensor,
                         connection, packet, centers, sizes, apply_weights,
                         inference_chunks, static_features):
    from torchrl.envs.utils import set_exploration_type, ExplorationType
    from online_refill import make_refill_policy, refill_slots, select_fresh

    if packet.get("supervision_horizon", 1) != 10:
        raise ValueError("The learner did not enable complete chunk supervision")
    n = env.num_envs
    student = make_refill_policy(base_policy, cfg, env, lee, checkpoint, checkpoint)
    if (student.required_history_frames != 1 or student.use_past_actions
            or student.action_frame != "current_observation_yaw_only_ego_flu"):
        raise ValueError("Require the original single-frame, yaw-ego Action Expert")
    target_mode = str(cfg.online.get("teacher_target_mode", "raw"))
    if packet.get("teacher_target_mode", "raw") != target_mode:
        raise ValueError("Actor/learner label modes differ")
    if abs(student.max_reference_speed-2.)>1e-6 or not bool((student.action_target_scale == 2.).all()):
        raise ValueError("Keep the original 2 m/s action contract")
    apply_weights(student, packet)
    predict = inference_chunks(student, int(cfg.online.get("inference_batch_size", 128)))
    version = initial_version = int(packet["step"])
    end = int(cfg.online.target_updates)
    capacity = int(cfg.online.learn_batch_capacity)
    minimum = int(cfg.online.get("minimum_batch_size", 1))
    if not 1 <= minimum <= min(n, capacity):
        raise ValueError("Invalid minimum online batch")
    route_rng = np.random.default_rng(int(cfg.env.route_seed)+1701)
    selector_rng = torch.Generator(device=env.device).manual_seed(int(cfg.seed)+31)
    active = torch.ones(n, dtype=torch.bool, device=env.device)
    pending_reset = torch.zeros_like(active)
    pending, buffer = {}, None
    physics = queries = samples = supervised_actions = replacements = completed = skipped = 0
    counts = {key: 0 for key in ("success", "collision", "out_of_bounds", "goal_brake_failed", "timeout")}
    test_resets = 0

    def online_predict(latent, goal, proprio, past, mask):
        nonlocal version, packet, buffer, samples, supervised_actions, skipped
        if buffer is not None:
            batch, label_metrics = buffer.consume(version, physics)
            count = len(batch["target"])
            if version < end and count >= minimum:
                diagnostics = {"available_online_states": count,
                               "fresh_batch_deficit": max(0, capacity-count),
                               "warmup_slots": int((student.warmup_chunks>0).sum()),
                               "refilled_slots": replacements, "completed_trajectories": completed,
                               "skipped_small_batches": skipped, "actor_pid": os.getpid(),
                               "full_fleet_resets": 1, "label_latency_physics_steps": 10,
                               "sample_chunk_start_physics_step": buffer.physics,
                               "ppo_query_every_physics_steps": 1, **label_metrics}
                connection.send({"command": "update", "batch": batch, "student_version": version,
                                 "physics_step": physics, "episode": completed, "diagnostics": diagnostics})
                packet = connection.recv()
                if int(packet["step"]) != version+1:
                    raise RuntimeError("One optimizer update per completed fresh chunk is required")
                version += 1
                samples += count
                supervised_actions += int(batch["target_mask"].sum())
                apply_weights(student, packet)
                if version == initial_version+1 or version % 10 == 0:
                    print({"update": version, "physics_step": physics, "fresh_states": count,
                           "supervised_actions": int(batch["target_mask"].sum()), **diagnostics}, flush=True)
            elif count:
                skipped += 1  # Drop it; NEVER replay, duplicate, or mix offline data.
        buffer = ChunkTeacherBuffer(latent, goal, proprio, pending["quaternion"],
                                    pending["selected"], version, physics, target_mode)
        return predict(latent, goal, proprio, past, mask)

    student.model.predict_action = online_predict
    td = env.reset()
    if not torch.allclose(td["info", "drone_state"][:, 0, :3],
                          env.fixed_scene["start_position"][:n].to(env.device), atol=1e-4, rtol=0):
        raise RuntimeError("Scene cloning offsets changed actual world flight routes")
    budget = (end-initial_version+student.bootstrap_action_chunks+33)*10
    stop_file = str(cfg.online.get("stop_file", ""))
    with torch.no_grad(), set_exploration_type(ExplorationType.MEAN):
        while physics < budget:
            index = physics % 10
            if index == 0:
                if stop_file and Path(stop_file).exists():
                    break
                ids = pending_reset.nonzero().flatten()
                if len(ids):
                    td = refill_slots(env, student, td, ids, route_rng)
                    replacements += len(ids)
                    active[ids] = True
                    pending_reset[ids] = False
            # PPO labels at the ACTUAL student's state before each command.
            teacher_sensor.update(env.dt, force_recompute=True)
            expert_td = td.clone()
            distance = (teacher_sensor.data.ray_hits_w-teacher_sensor.data.pos_w[:, None]).norm(dim=-1)
            distance = torch.nan_to_num(distance, nan=4., posinf=4.).clamp(0., 4.)
            expert_td["agents", "observation", "lidar"] = 4.-distance.reshape(n, 1, 36, 4)
            expert_td["agents", "observation", "dynamic_obstacle"] = torch.zeros(n, 1, 5, 10, device=env.device)
            state = td["info", "drone_state"][:, 0, :13]
            expert_td["agents", "observation", "static_obstacle"] = static_features(
                state[:, :3], expert_td["agents", "observation", "direction"], centers, sizes)
            teacher(expert_td)
            queries += 1
            world_target = expert_td["agents", "action"].reshape(n, 3)
            valid = active & ~student.goal_braking & torch.isfinite(world_target).all(-1)
            if student.goal_stop_enabled:
                valid &= (env.target_pos[:, 0]-state[:, :3]).norm(dim=-1)>student.goal_stop_distance
            if index == 0:
                selected, _ = select_fresh(valid & (student.warmup_chunks == 0), capacity, selector_rng)
                pending.update(quaternion=state[:, 3:7].clone(), selected=selected)
            student.set_active(active)
            before = version
            student(td)
            if index:
                assert before == version, "Weights changed inside the committed ten-command chunk"
            if buffer is None:
                raise RuntimeError("Student never captured a chunk-start observation")
            # Every target uses the SAME yaw frame as that chunk's output.
            raw_target = student._world_to_ego(world_target, buffer.quaternion)/2.
            buffer.record(index, raw_target, valid & ~student.goal_braking)
            td = env.step(td)["next"]
            physics += 1
            stats = td["stats"]
            success = stats["reach_goal"].flatten().bool()
            collision = stats["collision"].flatten().bool()
            oob = stats["out_of_bounds"].flatten().bool()
            timeout = td["truncated"].flatten().bool()
            goal_distance = (env.target_pos[:, 0]-td["info", "drone_state"][:, 0, :3]).norm(dim=-1)
            brake_failed = student.goal_braking & (goal_distance>student.goal_stop_distance)
            finished = active & (success | collision | oob | brake_failed | timeout)
            remaining = finished.clone()
            for key, done in (("collision", collision), ("out_of_bounds", oob),
                              ("goal_brake_failed", brake_failed), ("success", success), ("timeout", timeout)):
                hit = remaining & done
                counts[key] += int(hit.sum())
                remaining &= ~hit
            completed += int(finished.sum())
            active[finished] = False
            pending_reset |= finished
            if bool(cfg.online.get("test_force_refill", False)) and physics == 20:
                forced = torch.tensor([0, n-1], device=env.device)
                active[forced] = False
                pending_reset[forced] = True
                test_resets += len(forced)
            if physics % 100 == 0:
                print(f"[chunk actor] physics={physics} active={int(active.sum())}/{n} "
                      f"updates={version} refilled={replacements}", flush=True)
            if version >= end and physics % 10 == 0:
                break
    requested_stop = bool(stop_file and Path(stop_file).exists())
    if version < end and not requested_stop:
        raise RuntimeError("Online chunk supervision made insufficient progress")
    if test_resets and replacements < test_resets:
        raise RuntimeError("Partial-refill test was not exercised")
    connection.send({"command": "finish", "episodes": completed})
    ack = connection.recv()
    if int(ack["step"]) != version:
        raise RuntimeError("Final actor/learner versions differ")
    connection.close()
    return {"updates": version, "start_update": initial_version, "physics_steps": physics,
            "teacher_queries": queries, "fresh_supervised_states": samples,
            "fresh_supervised_actions": supervised_actions, "num_envs": n,
            "online_batch_capacity": capacity, "actor_pid": os.getpid(), "full_fleet_resets": 1,
            "stopped_by_request": requested_stop, "minimum_online_batch": minimum,
            "uses_offline_replay": False, "teacher_controls_student": False,
            "refill_enabled": True, "teacher_target_mode": target_mode, "supervision_horizon": 10,
            "completed_trajectories": completed, "refilled_slots": replacements,
            "forced_test_resets": test_resets, "skipped_small_batches": skipped,
            "training_counts_not_heldout_eval": counts, "query_interval_steps": 1,
            "replan_interval_steps": 10, "supervised_action_index": "0:9",
            "label_latency_physics_steps": 10, "target_uses_chunk_start_yaw": True,
            "target_semantics": "teacher corrections along actual student trajectory, not PPO counterfactual",
            "post_terminal_action_masked": True, "weights_fixed_inside_chunk": True,
            "peak_allocated_gib": torch.cuda.max_memory_allocated()/2**30,
            "peak_reserved_gib": torch.cuda.max_memory_reserved()/2**30}
